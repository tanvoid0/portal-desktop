#!/usr/bin/env node
/**
 * Regenerate the TypeScript types that mirror Rust, then write the barrel.
 *
 * ts-rs exports one file per type and no index, so `export type { X } from
 * './generated'` has nothing to resolve without this. Kept as a script rather
 * than a checked-in hand-written index, because a stale barrel is the same
 * drift the generator exists to remove.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const GENERATED = ['src/lib/domains/coder/generated', 'src/lib/domains/disk/generated'];

execFileSync(
  'cargo',
  ['test', '--manifest-path', 'src-tauri/portal-core/Cargo.toml', 'export_bindings'],
  {
    stdio: 'inherit',
  }
);

for (const dir of GENERATED) {
  const types = readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .map((f) => f.slice(0, -3))
    .sort();

  const barrel =
    '// Generated by scripts/gen-types.mjs. Do not edit.\n' +
    types.map((t) => `export type { ${t} } from './${t}';`).join('\n') +
    '\n';

  writeFileSync(join(dir, 'index.ts'), barrel);
  console.log(`${dir}/index.ts — ${types.length} types`);
}

// ts-rs emits its own formatting, which `prettier --check .` rejects. Formatting
// here rather than ignoring the directory keeps the output canonical: CI asserts
// that regenerating is a no-op, and that only holds if what the generator writes
// is byte-identical to what is committed.
execFileSync('npx', ['prettier', '--write', ...GENERATED], {
  stdio: 'inherit',
  shell: process.platform === 'win32',
});
