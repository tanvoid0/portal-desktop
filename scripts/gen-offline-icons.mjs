// Bundles the Iconify icons referenced by string name (e.g. 'logos:react') so
// @iconify/svelte never hits the network. Re-run after adding a new name:
//   node scripts/gen-offline-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const SETS = ['logos', 'mdi', 'codicon', 'simple-icons'];
const re = new RegExp(`['"\`](${SETS.join('|')}):([a-z0-9-]+)['"\`]`, 'g');
const wanted = Object.fromEntries(SETS.map((s) => [s, new Set()]));

function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(svelte|ts)$/.test(f.name) && !f.name.startsWith('offline.generated')) {
      for (const m of fs.readFileSync(p, 'utf8').matchAll(re)) wanted[m[1]].add(m[2]);
    }
  }
}
walk('src');

const cols = [];
for (const set of SETS) {
  const json = require(`@iconify-json/${set}/icons.json`);
  const icons = {};
  for (const name of wanted[set]) {
    const alias = json.aliases?.[name];
    const base = alias ? alias.parent : name;
    if (!json.icons[base]) {
      console.warn(`missing ${set}:${name}`);
      continue;
    }
    icons[base] = json.icons[base];
    if (alias) cols.push({ prefix: set, icons: {}, aliases: { [name]: alias } });
  }
  cols.push({ prefix: set, icons, width: json.width, height: json.height });
}

const out =
  `// GENERATED by scripts/gen-offline-icons.mjs — do not edit.\n` +
  `import { addCollection } from '@iconify/svelte';\n\n` +
  cols.map((c) => `addCollection(${JSON.stringify(c)});`).join('\n') +
  '\n';
fs.mkdirSync('src/lib/icons', { recursive: true });
fs.writeFileSync('src/lib/icons/offline.generated.ts', out);
console.log('wrote', cols.length, 'collections');
