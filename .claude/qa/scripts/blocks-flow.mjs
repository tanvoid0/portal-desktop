import { open } from './app.mjs';
import { dismissVault } from './util.mjs';
const app = await open('automation/blocks');
const p = app.page;
await dismissVault(p);
await p.getByRole('button', { name: /^Create$/ }).first().click();
await p.waitForTimeout(600);
const dlg = p.getByRole('dialog');
await dlg.getByPlaceholder('e.g., Install Dependencies').fill('QA block 日本語 🚀 long-name-long-name-long-name-long-name');
await dlg.getByPlaceholder('Describe what this block does.').fill('QA fixture');
await dlg.getByPlaceholder('e.g., npm install').fill('echo qa');
await dlg.getByRole('button', { name: /^Create$/ }).dblclick();
await p.waitForTimeout(1500);
console.log('dialog open after create', await p.getByRole('dialog').count());
await p.getByPlaceholder('Search blocks...').fill('QA block');
await p.waitForTimeout(500);
console.log(await app.shot('sweep-blocks-qa-created'));
const del = p.getByRole('button', { name: /^Delete.*QA block/ });
console.log('delete btns', await del.count(), await p.locator('[data-slot=card]').count());
await app.done();
