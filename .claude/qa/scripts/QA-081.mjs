import { open } from './app.mjs';
const app = await open('tasks?project=all&view=board'); const p = app.page;
const sel=()=>p.getByText(/\d+ selected/).allInnerTexts();
const dlg=async()=>(await p.getByRole('dialog').count()+await p.getByRole('alertdialog').count());
const clearAll=p.getByRole('button',{name:'Clear All'}); if(await clearAll.count()) await clearAll.first().click();
await p.keyboard.press('Control+m'); await p.waitForTimeout(300);
const s=p.getByPlaceholder('Search tasks...'); await s.click(); await s.fill('QA Cmp'); await p.waitForTimeout(400);
await p.keyboard.press('Control+a'); await p.waitForTimeout(300);
console.log('A) ctrl+a in search: selected', await sel(), '| selection text:', await p.evaluate(()=>{const e=document.activeElement;return e.value?.slice(e.selectionStart,e.selectionEnd)}));
await s.fill(''); await p.waitForTimeout(400);
await p.locator('body').click({position:{x:700,y:60}}); await p.keyboard.press('Control+a'); await p.waitForTimeout(300);
console.log('B) ctrl+a outside field: selected', await sel());
await p.keyboard.press('Delete'); await p.waitForTimeout(500); console.log('confirm open', await p.getByRole('alertdialog').count());
await app.shot('QA-081-after-bulk-delete-confirm');
await p.keyboard.press('Escape'); await p.waitForTimeout(500);
console.log('C) esc on confirm: dialogs', await dlg(), 'selected', await sel());
await app.shot('QA-081-after-esc-keeps-selection');
await p.keyboard.press('Control+f'); await p.waitForTimeout(400); const a=await dlg(); await p.keyboard.press('Escape'); await p.waitForTimeout(400);
console.log('D) filter dialog open', a, 'closed ->', await dlg(), 'selected', await sel());
await p.locator('body').click({position:{x:700,y:60}});
await p.keyboard.press('Control+h'); await p.waitForTimeout(400); const b=await dlg(); await p.keyboard.press('Escape'); await p.waitForTimeout(400);
console.log('E) shortcuts dialog open', b, 'closed ->', await dlg(), 'selected', await sel());
await p.locator('body').click({position:{x:700,y:60}});
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
console.log('F) esc with no dialog: multiselect bar', await p.getByText(/selected/).count());
await app.done();
