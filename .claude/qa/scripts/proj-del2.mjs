import { open } from './app.mjs';
import { dismissVault } from './util.mjs';
const app = await open('projects');
const p = app.page;
await dismissVault(p);
await p.getByText('Loading projects...').waitFor({ state: 'detached', timeout: 20000 }).catch(()=>{});
await p.getByPlaceholder('Search projects...').fill('QA project');
await p.waitForTimeout(1000);
await p.getByText('QA project edited').first().click({ button: 'right' });
await p.getByRole('menuitem', { name: 'Delete' }).click();
await p.waitForTimeout(600);
console.log('dialog', await p.locator('[role=alertdialog],[role=dialog]').allInnerTexts());
console.log(await app.shot('sweep-projects-delete-confirm-qa'));
await p.locator('[role=alertdialog],[role=dialog]').getByRole('button', { name: /Delete|Continue/ }).click();
await p.waitForTimeout(1500);
console.log('remaining', await p.getByText('QA project edited').count());
const r = await p.evaluate(async () => (await window.__TAURI_INTERNALS__.invoke('get_all_projects')).filter(x=>/^QA/.test(x.name)).length);
console.log('backend QA projects', r);
await app.done();
