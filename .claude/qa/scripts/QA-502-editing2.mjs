import { open } from './app.mjs';
const app = await open('database');
const p = app.page;
await p.waitForTimeout(1500);
await p.getByText('qa502.db', { exact: true }).first().click();
await p.waitForTimeout(400);
await p.getByText('qa_no_pk', { exact: true }).click();
await p.waitForTimeout(1000);
await p.mouse.wheel(0, -5000);
await p.waitForTimeout(300);
console.log('Insert row button count:', await p.getByRole('button', { name: 'Insert row' }).count());
console.log('rows:', await p.locator('tbody tr').count());
const cell = p.locator('tbody tr').first().locator('td').first();
await cell.click();
await p.waitForTimeout(400);
console.log('input count after click (should be 0, no edit):', await p.locator('input, textarea').count());
console.log('delete icon count (should be 0):', await p.locator('tbody tr').first().locator('button').count());
await app.shot('QA-502-no-pk-table');
await app.done();
