import { open } from './app.mjs';
import { dismissVault } from './util.mjs';
const app = await open('automation/blocks');
const p = app.page;
await dismissVault(p);
await p.getByRole('button', { name: /^Create$/ }).first().click();
const dlg = p.getByRole('dialog');
await dlg.getByPlaceholder('e.g., Install Dependencies').fill('QA block single');
await dlg.getByPlaceholder('Describe what this block does.').fill('QA fixture');
await dlg.getByPlaceholder('e.g., npm install').fill('echo qa');
await dlg.getByRole('button', { name: /^Create$/ }).click();
await p.waitForTimeout(1200);
await p.getByPlaceholder('Search blocks...').fill('QA block');
await p.waitForTimeout(500);
const card = p.locator('[data-slot=card]', { hasText: 'QA block single' }).first();
console.log('card buttons', await card.getByRole('button').evaluateAll(els=>els.map(e=>e.getAttribute('aria-label')||e.title||'?')));
await card.getByRole('button').last().click();
await p.waitForTimeout(500);
console.log('dialog after delete click:', await p.locator('[role=dialog],[role=alertdialog]').allInnerTexts());
console.log(await app.shot('sweep-blocks-delete-click-2'));
await p.waitForTimeout(800);
console.log('card still there', await p.locator('[data-slot=card]', { hasText: 'QA block single' }).count());
await app.done();
